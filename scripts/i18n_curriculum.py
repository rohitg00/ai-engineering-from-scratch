#!/usr/bin/env python3
"""Emit the curriculum + glossary sections of site/i18n.zh-Hant.js.

Translations are keyed by term / phase id / lesson order so the English source
strings are read straight out of site/data.js and never retyped: a key can
therefore never drift from what the site actually renders. Mismatched lesson
counts fail loudly instead of silently shifting every title by one.
"""
import ast, json, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def load_data():
    js = """
    const vm=require('vm'),fs=require('fs');const s={};vm.createContext(s);
    vm.runInContext(fs.readFileSync('site/data.js','utf8'),s);
    const {PHASES,GLOSSARY}=vm.runInContext('({PHASES,GLOSSARY})',s);
    console.log(JSON.stringify({PHASES,GLOSSARY}));
    """
    out = subprocess.run(['node','-e',js], cwd=ROOT, capture_output=True, text=True, check=True)
    return json.loads(out.stdout)

def emit(pairs, title, seen):
    lines = [f'\n  /* ── {title} ' + '─'*max(0, 58-len(title)) + ' */']
    for en, zh in pairs:
        if not zh or not en or en in seen:
            continue
        seen.add(en)
        k, v = json.dumps(en, ensure_ascii=False), json.dumps(zh, ensure_ascii=False)
        lines.append(f'  {k}:\n    {v},' if len(k)+len(v) > 92 else f'  {k}: {v},')
    return '\n'.join(lines)

